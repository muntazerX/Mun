// Helper to find the price tier for any item based on copper value
export function getItemPriceTier(copperValue: number): PriceTier {
  for (let i = TRADE_SCALE.length - 2; i >= 0; i--) {
    if (copperValue >= TRADE_SCALE[i].copperValue) {
      return TRADE_SCALE[i];
    }
  }
  return TRADE_SCALE[0];
}
